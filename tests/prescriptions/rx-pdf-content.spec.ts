/**
 * V2-09c 09C-04 (R-12, Q-9; PWA D-7): what the prescription PDF says and where it prints. Pure renders of fixed synthetic payloads (the goldens pin the whole
 * document; these cases name each rule):
 *   - a medicine with no stored timing prints NO timing (the retired template printed "After food");
 *   - the document title and the download file name carry no patient name; the dates the document writes are the version's signature;
 *   - every date is the clinic's (ADR-016): the same bytes whatever zone the server runs in, with a signature that is the next day in the clinic's zone;
 *   - the structured exam prints (general signs, abnormal systems with findings, side and note, the normal ones in one line);
 *   - a complaint prints a duration only when it has one; the footer keeps the product line on blank paper and adds "Rx v{n} · Page x of y" (Q-9 ruling);
 *   - on pre-printed stationery nothing is printed inside the clinic's top and bottom margins, on any page, on A4 or A5, with the clinic's own numbers.
 */
import { afterEach, describe, expect, it } from "vitest";
import { renderPrescriptionPdf } from "@/features/prescriptions/pdf/generator";
import { buildRxContent, rxFileName } from "@/features/prescriptions/pdf/content";
import { effectiveMargins } from "@/features/prescriptions/pdf/layout";
import { examPrintLines } from "@/features/consultation/exam-text";
import { clinicDateText, ymdLabel } from "@/lib/datetime";
import { PAGE_A4, PAGE_A5, pdfInfo, pdfPageSizes, pdfText, pdfTextLines, pdfTextPositions } from "../helpers/pdf-text";
import { basePayload, longPayload } from "../helpers/rx-pdf-fixtures";

const originalTz = process.env.TZ;
afterEach(() => {
  if (originalTz === undefined) delete process.env.TZ;
  else process.env.TZ = originalTz;
});

const text = async (over: Parameters<typeof basePayload>[0] = {}) => pdfText(await renderPrescriptionPdf(basePayload(over))).replace(/\u0095/g, "•");

describe("no invented text", () => {
  it("a medicine with no stored timing prints no timing; a stored one prints as stored", async () => {
    const out = await text();
    expect(out).not.toContain("After food\nCetirizine"); // order guard: the cetirizine row follows the paracetamol row
    const lines = out.split("\n");
    const rowOfCetirizine = lines.indexOf("Cetirizine 10");
    expect(rowOfCetirizine).toBeGreaterThan(-1);
    // Its row: name, note, dosage, duration (no timing cell text between dosage and duration).
    expect(lines.slice(rowOfCetirizine, rowOfCetirizine + 5).join("|")).toBe("Cetirizine 10|Note: May cause drowsiness|0-0-1|5 |days");
    const onlyNull = await text({ medications: [{ medicine_name: "Plain Tablet", dosage: "1-0-1", timing: null, duration: "5 days" }] });
    expect(onlyNull).not.toContain("After food");
    expect(onlyNull).not.toContain("Before food");
    expect(await text({ medications: [{ medicine_name: "Plain Tablet", dosage: "1-0-1", timing: "Before food", duration: "5 days" }] })).toContain("Before food");
  });

  it("a complaint prints a duration only when it has one, and never an invented unit", () => {
    const base = basePayload();
    const content = buildRxContent({
      ...base,
      visit: { ...base.visit, chief_complaints: [{ symptom: "Fever", duration_val: 3, duration_unit: "days" }, { symptom: "Cough" }, { symptom: "Rash", duration_val: 2 }] },
    });
    expect(content.complaints).toEqual(["Fever (3 days)", "Cough", "Rash (2)"]);
  });

  it("the footer keeps the product line on blank paper, adds the page line, and pre-printed stationery has no clinic block and no product line", async () => {
    const blank = await text();
    expect(blank).toContain("Generated by ClinicOS • Confidential Medical Record");
    expect(blank).toContain("Rx v1 · Page 1 of 1");
    expect(blank).toContain("Synthetic Care Clinic");
    const preprinted = await text({ letterhead_mode: "preprinted_letterhead" });
    expect(preprinted).not.toContain("Generated by ClinicOS");
    expect(preprinted).not.toContain("Synthetic Care Clinic");
    expect(preprinted).not.toContain("Asha Example\nMBBS");
    expect(preprinted).toContain("Rx v1 · Page 1 of 1");
    // The signature block still names the doctor on stationery.
    expect(preprinted).toContain("Dr. Asha Example");
  });

  it("the amendment banner and the regenerated notice are the version's own words", async () => {
    const amended = await text({ version: 2, amendment_reason: "Corrected dose", amended_at: "2026-11-21T04:00:00.000Z" });
    expect(amended).toContain("AMENDED PRESCRIPTION (v2) • 21 Nov 2026");
    expect(amended).toContain("Reason: Corrected dose");
    expect(amended).toContain("Rx v2 · Page 1 of 1");
    expect(await text({ regenerated_notice: "Regenerated copy, not the archived original" })).toContain("Regenerated copy, not the archived original");
  });
});

describe("no patient name in the title or the file name (PWA D-7); the dates are the version's signature", () => {
  it("the document title is 'Prescription v{n}' and the file name is built from the visit date and the version", async () => {
    const payload = basePayload();
    const pdf = await renderPrescriptionPdf(payload);
    const info = pdfInfo(pdf);
    expect(info.title).toBe("Prescription v1");
    expect(info.title).not.toContain("Ravi");
    expect(info.title).not.toContain("Synthetic");
    expect(rxFileName(payload)).toBe("Prescription-2026-11-20-v1.pdf");
    expect(rxFileName(basePayload({ version: 3 }))).toBe("Prescription-2026-11-20-v3.pdf");
    expect(rxFileName(payload)).not.toMatch(/Ravi|Synthetic/);
  });

  it("the creation and modification date are the header's signature (UTC), so a signed version renders to the same bytes", async () => {
    const info = pdfInfo(await renderPrescriptionPdf(basePayload({ signed_at: "2026-11-20T10:30:00.000Z" })));
    expect(info.creationDate).toBe("D:20261120103000Z");
    expect(info.modDate).toBe("D:20261120103000Z");
    const other = pdfInfo(await renderPrescriptionPdf(basePayload({ signed_at: "2026-11-21T04:05:00.000Z" })));
    expect(other.creationDate).toBe("D:20261121040500Z");
  });
});

describe("dates are the clinic's, not the server's (ADR-016)", () => {
  // 19:00 UTC on 20 Nov is 00:30 on 21 Nov in Asia/Kolkata and still 20 Nov in UTC and in Los Angeles.
  const lateSigned = "2026-11-20T19:00:00.000Z";

  it("with the server zone set to UTC and to Los Angeles the bytes are the same and the signature date is the clinic's next day", async () => {
    process.env.TZ = "UTC";
    const inUtc = await renderPrescriptionPdf(basePayload({ signed_at: lateSigned }));
    process.env.TZ = "America/Los_Angeles";
    const inLa = await renderPrescriptionPdf(basePayload({ signed_at: lateSigned }));
    expect(Buffer.compare(inUtc, inLa)).toBe(0);
    expect(pdfText(inUtc)).toContain("Signed on 21 Nov 2026");
    expect(pdfText(inUtc)).not.toContain("Signed on 20 Nov 2026");
  });

  it("another clinic zone moves the date the same way", async () => {
    expect(pdfText(await renderPrescriptionPdf(basePayload({ signed_at: lateSigned, timezone: "America/Los_Angeles" })))).toContain("Signed on 20 Nov 2026");
  });

  it("an unsigned rendering falls back to the visit date, and an unusable zone to the default", () => {
    expect(buildRxContent(basePayload({ signed_at: null })).signature.signedOn).toBe("Signed on 2026-11-20");
    expect(buildRxContent(basePayload({ signed_at: lateSigned, timezone: "Not/AZone" })).signature.signedOn).toBe("Signed on 21 Nov 2026");
  });
});

describe("the date text is a fixed table (the same on every runtime)", () => {
  it("ymdLabel and clinicDateText", () => {
    expect(ymdLabel("2026-01-05")).toBe("5 Jan 2026");
    expect(ymdLabel("2026-12-31")).toBe("31 Dec 2026");
    expect(clinicDateText("2026-11-20T19:00:00.000Z", "Asia/Kolkata")).toBe("21 Nov 2026");
    expect(clinicDateText("2026-11-20T19:00:00.000Z", "UTC")).toBe("20 Nov 2026");
    expect(() => ymdLabel("2026-02-30")).toThrow(RangeError);
  });
});

describe("the structured exam", () => {
  const data = {
    specialty: "general_physician",
    general_exam: { pallor: true, icterus: false, cyanosis: false, clubbing: false, lymphadenopathy: true, edema: false },
    exam: {
      template_id: "fever",
      systems: {
        gen: { abnormal: false, findings: [], side: null, note: null },
        cvs: { abnormal: false, findings: [], side: null, note: null },
        rs: { abnormal: true, findings: ["Crepts", "Wheeze"], side: "Right", note: "Mild" },
      },
    },
  };

  it("lists the general signs, each abnormal system with its findings and note, and the normal systems in one line (labels, not boilerplate)", () => {
    const lines = examPrintLines(data);
    expect(lines).toEqual({ general: "Pallor, Lymphadenopathy", abnormal: ["RS: Crepts, Wheeze (Right) · Mild"], normal: "General, CVS" });
  });

  it("an abnormal system with a side and no findings, and one with nothing chosen", () => {
    const rs = { template_id: "resp", systems: { rs: { abnormal: true, findings: ["Crepts", "Wheeze"], side: "Right", note: null }, cvs: { abnormal: true, findings: [], side: null, note: null } } };
    const out = examPrintLines({ specialty: "general_physician", exam: rs });
    expect(out?.abnormal).toEqual(["RS: Crepts, Wheeze (Right)", "CVS: Abnormal"]);
    expect(out?.normal).toBeNull();
  });

  it("nothing entered, another specialty, an unknown template or no data: no exam section", () => {
    expect(examPrintLines(null)).toBeNull();
    expect(examPrintLines({ specialty: "dental", odontogram: [] })).toBeNull();
    expect(examPrintLines({ specialty: "general_physician", exam: { template_id: "no_such_template", systems: {} } })).toBeNull();
    expect(examPrintLines({ specialty: "general_physician", general_exam: { pallor: false } })).toBeNull();
  });

  it("the PDF prints the exam lines under an Examination heading, and omits the heading when there is no exam", async () => {
    const out = await text();
    expect(out).toContain("EXAMINATION");
    expect(out).toContain("General signs: \nPallor");
    expect(out).toContain("RS: Crepts, Wheeze (Right) · Basal");
    expect(out).toContain("Normal: \nGeneral, CVS, PA");
    const base = basePayload();
    expect(await text({ visit: { ...base.visit, exam: null } })).not.toContain("EXAMINATION");
  });
});

describe("print margins are honoured (pre-printed stationery)", () => {
  async function positions(over: Parameters<typeof basePayload>[0]) {
    const pdf = await renderPrescriptionPdf(over && over.medications && over.medications.length > 5 ? { ...longPayload(), ...over } : basePayload(over));
    return { pdf, pos: pdfTextPositions(pdf), sizes: pdfPageSizes(pdf) };
  }

  it.each([
    ["A4", { top: 114, bottom: 60 }],
    ["A4", { top: 200, bottom: 100 }],
    ["A5", { top: 90, bottom: 50 }],
    ["A5", { top: 0, bottom: 0 }],
  ] as const)("%s with margins %j: no text above the top margin or below the bottom margin on any page", async (paper, margins) => {
    const { pos, sizes } = await positions({
      paper_size: paper,
      letterhead_mode: "preprinted_letterhead",
      letterhead_margins: margins,
      medications: longPayload().medications,
      advice: longPayload().advice,
    });
    const height = paper === "A4" ? PAGE_A4.height : PAGE_A5.height;
    expect(sizes.length).toBeGreaterThanOrEqual(2);
    expect(pos.length).toBeGreaterThan(20);
    for (const p of pos) {
      expect(p.yFromTop, `${p.text} on page ${p.page}`).toBeGreaterThanOrEqual(margins.top);
      expect(p.yFromTop, `${p.text} on page ${p.page}`).toBeLessThanOrEqual(height - margins.bottom);
    }
    // The continuation line and the footer are drawn on every page after the first / every page.
    expect(pos.some((p) => p.page === 2 && p.text.includes("Rx Continuation"))).toBe(true);
    expect(pos.filter((p) => p.text.includes("· Page ")).length).toBe(sizes.length);
  });

  it("blank paper uses the design margins and ignores the clinic's stationery margins", async () => {
    const { pos } = await positions({ letterhead_mode: "blank_paper", letterhead_margins: { top: 250, bottom: 250 } });
    expect(Math.min(...pos.map((p) => p.yFromTop))).toBeLessThan(80);
  });

  it("margins that would leave no room are reduced to leave the prescription 220 points, and a missing or odd value falls back to the defaults", () => {
    expect(effectiveMargins({ letterhead_margins: { top: 300, bottom: 300 }, paper_size: "A5" })).toEqual({ top: 187, bottom: 187 });
    expect(effectiveMargins({ letterhead_margins: { top: 300, bottom: 300 }, paper_size: "A4" })).toEqual({ top: 300, bottom: 300 });
    expect(effectiveMargins({ letterhead_margins: null, paper_size: "A4" })).toEqual({ top: 110, bottom: 60 });
    expect(effectiveMargins({ letterhead_margins: { top: -5, bottom: 999 }, paper_size: "A4" })).toEqual({ top: 0, bottom: 300 });
  });

  it("the page size follows the version's paper (and the lines still print)", async () => {
    const a5 = await renderPrescriptionPdf(basePayload({ paper_size: "A5" }));
    expect(pdfPageSizes(a5).every((s) => s.width === PAGE_A5.width && s.height === PAGE_A5.height)).toBe(true);
    expect(pdfTextLines(a5).join("\n")).toContain("Paracetamol 650");
  });
});
