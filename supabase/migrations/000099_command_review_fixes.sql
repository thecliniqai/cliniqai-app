-- 3. G-1 every slot conflict, not only the first ------------------------------------------------------------------------------
CREATE FUNCTION private.slot_conflicts(
    p_tenant_id uuid,
    p_doctor_id uuid,
    p_start timestamptz,
    p_duration_minutes integer,
    p_timezone text
)
RETURNS text[]
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
    v_sched jsonb;
    v_day jsonb;
    v_local timestamp;
    v_minute integer;
    v_shift jsonb;
    v_in_shift boolean := false;
    v_off_duty boolean := false;
    v_out text[] := ARRAY[]::text[];
    v_end timestamptz := p_start + make_interval(mins => p_duration_minutes);
BEGIN
    -- The doctor is an active clinician of the clinic (G-9).
    SELECT m.availability_schedule INTO v_sched
      FROM public.memberships m
     WHERE m.tenant_id = p_tenant_id AND m.user_id = p_doctor_id AND m.status = 'active'
       AND authz.role_has_permission(m.role, 'consultations:edit');
    IF NOT FOUND THEN
        RAISE EXCEPTION 'DOCTOR_NOT_FOUND' USING ERRCODE = 'P0002';
    END IF;

    -- 1. The doctor's working shifts, on the clinic-local weekday and time of day. No schedule stored = no restriction.
    IF v_sched IS NOT NULL THEN
        v_local := p_start AT TIME ZONE p_timezone;
        v_minute := extract(hour FROM v_local)::integer * 60 + extract(minute FROM v_local)::integer;
        v_day := v_sched -> (ARRAY['monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday', 'sunday']
                             )[extract(isodow FROM v_local)::integer];
        IF v_day IS NULL OR NOT coalesce((v_day ->> 'enabled')::boolean, false) THEN
            v_off_duty := true;
        ELSE
            FOR v_shift IN SELECT s.value FROM jsonb_array_elements(v_day -> 'shifts') s LOOP
                IF v_minute >= (substr(v_shift ->> 'start', 1, 2)::integer * 60 + substr(v_shift ->> 'start', 4, 2)::integer)
                   AND v_minute + p_duration_minutes <= (substr(v_shift ->> 'end', 1, 2)::integer * 60 + substr(v_shift ->> 'end', 4, 2)::integer) THEN
                    v_in_shift := true;
                    EXIT;
                END IF;
            END LOOP;
            v_off_duty := NOT v_in_shift;
        END IF;
        IF v_off_duty THEN
            v_out := v_out || 'off_duty';
        END IF;
    END IF;

    -- 2. Schedule blocks: the doctor's own and clinic-wide (doctor_id null).
    IF EXISTS (SELECT 1 FROM public.schedule_blocks b
                WHERE b.tenant_id = p_tenant_id AND (b.doctor_id = p_doctor_id OR b.doctor_id IS NULL)
                  AND b.start_time < v_end AND b.end_time > p_start) THEN
        v_out := v_out || 'blocked';
    END IF;

    -- 3. A booked visit of the doctor: the rows visits_no_double_booking (000063) keeps apart.
    IF EXISTS (SELECT 1 FROM public.visits v
                WHERE v.tenant_id = p_tenant_id AND v.doctor_id = p_doctor_id AND v.origin_type = 'scheduled'
                  AND v.scheduled_at IS NOT NULL AND NOT v.is_overbooked AND v.status NOT IN ('cancelled', 'no_show')
                  AND public.visit_slot(v.scheduled_at, v.estimated_duration_minutes) && tstzrange(p_start, v_end, '[)')) THEN
        v_out := v_out || 'taken';
    END IF;
    RETURN v_out;
END;
$$;
REVOKE ALL ON FUNCTION private.slot_conflicts(uuid, uuid, timestamptz, integer, text) FROM PUBLIC, anon, authenticated, service_role;
COMMENT ON FUNCTION private.slot_conflicts(uuid, uuid, timestamptz, integer, text) IS
    'V2-07 07-04a (G-1, G-9): every reason a doctor cannot take [start, start + duration): off_duty (outside the clinic-local shifts), blocked (a doctor or clinic block overlaps), taken (a non-overbooked scheduled visit overlaps); an empty array when free. DOCTOR_NOT_FOUND (P0002) unless the doctor is an active clinician of the clinic. Replaces private.slot_conflict, which reported only the first.';

-- 4. F-4 command_claim / command_complete: no API grant, the system path is the service role's ------------------
CREATE OR REPLACE FUNCTION private.command_claim(
    p_tenant_id uuid,
    p_client_request_id uuid,
    p_command text,
    p_request_hash text,
    p_system_actor text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
SET lock_timeout = '2s'
AS $$
DECLARE
    v_uid uuid := (SELECT auth.uid());
    v_inserted integer;
    v_row private.command_results;
BEGIN
    IF p_client_request_id IS NULL THEN
        RAISE EXCEPTION 'CLIENT_REQUEST_ID_REQUIRED' USING ERRCODE = 'P0001';
    END IF;
    IF p_tenant_id IS NULL OR p_command IS NULL OR p_command = '' OR p_request_hash IS NULL OR p_request_hash = '' THEN
        RAISE EXCEPTION 'INPUT_INVALID' USING ERRCODE = 'P0001';
    END IF;
    -- A session is a user (no system actor); the system path has no session. The command function checks this first.
    IF (v_uid IS NULL) = (p_system_actor IS NULL) THEN
        RAISE EXCEPTION 'ACTOR_INVALID' USING ERRCODE = 'P0001';
    END IF;
    -- 000099 (F-4): the system path is the service role's (the `role` setting survives the definer boundary, as in
    -- record_payment); nobody else can claim as a system actor.
    IF p_system_actor IS NOT NULL AND current_setting('role', true) IS DISTINCT FROM 'service_role' THEN
        RAISE EXCEPTION 'ACTOR_INVALID' USING ERRCODE = 'P0001';
    END IF;
    -- Defence in depth: a user claims only in the active, full clinic (the stored result of another clinic is never read).
    IF v_uid IS NOT NULL AND p_tenant_id IS DISTINCT FROM (SELECT authz.full_tenant_ids() LIMIT 1) THEN
        RAISE EXCEPTION 'NOT_FOUND' USING ERRCODE = 'P0002';
    END IF;

    -- A concurrent duplicate waits here on the primary key until the first transaction ends (lock_timeout 2s), then
    -- reads the committed row below; if the first rolled back it claims fresh.
    INSERT INTO private.command_results (tenant_id, client_request_id, command, actor_id, system_actor, request_hash)
    VALUES (p_tenant_id, p_client_request_id, p_command, v_uid, p_system_actor, p_request_hash)
    ON CONFLICT (tenant_id, client_request_id) DO NOTHING;
    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    IF v_inserted = 1 THEN
        RETURN NULL;
    END IF;

    SELECT r.* INTO v_row
      FROM private.command_results r
     WHERE r.tenant_id = p_tenant_id AND r.client_request_id = p_client_request_id;
    IF NOT FOUND
        OR v_row.command IS DISTINCT FROM p_command
        OR v_row.actor_id IS DISTINCT FROM v_uid
        OR v_row.system_actor IS DISTINCT FROM p_system_actor
        OR v_row.request_hash IS DISTINCT FROM p_request_hash
        -- Same request but no stored result: the claim belongs to a command still open in this very transaction.
        OR v_row.result IS NULL THEN
        RAISE EXCEPTION 'IDEMPOTENCY_MISMATCH' USING ERRCODE = 'P0001';
    END IF;

    RETURN v_row.result || jsonb_build_object('replayed', true);
END;
$$;
REVOKE ALL ON FUNCTION private.command_claim(uuid, uuid, text, text, text) FROM PUBLIC, anon, authenticated, service_role;
COMMENT ON FUNCTION private.command_claim(uuid, uuid, text, text, text) IS
    'V2-07 R-2 (000099 F-4: no API grant; only the definer commands call it): claims (tenant, client_request_id) for a command. NULL = fresh claim; a stored result of the same command, actor and request hash = replay ({..., replayed: true}); anything else IDEMPOTENCY_MISMATCH. CLIENT_REQUEST_ID_REQUIRED without an id.';

CREATE OR REPLACE FUNCTION private.command_complete(
    p_tenant_id uuid,
    p_client_request_id uuid,
    p_result jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
SET lock_timeout = '2s'
AS $$
DECLARE
    v_uid uuid := (SELECT auth.uid());
BEGIN
    IF p_result IS NULL OR jsonb_typeof(p_result) <> 'object' THEN
        RAISE EXCEPTION 'INPUT_INVALID' USING ERRCODE = 'P0001';
    END IF;
    -- Only the claim of THIS transaction can be completed, by the actor that made it: an open row of a concurrent
    -- command (result still NULL, not visible to us until it commits) is never written here.
    UPDATE private.command_results r
       SET result = p_result
     WHERE r.tenant_id = p_tenant_id
       AND r.client_request_id = p_client_request_id
       AND r.result IS NULL
       AND r.actor_id IS NOT DISTINCT FROM v_uid;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'COMMAND_NOT_CLAIMED' USING ERRCODE = 'P0001';
    END IF;
    RETURN p_result;
END;
$$;
REVOKE ALL ON FUNCTION private.command_complete(uuid, uuid, jsonb) FROM PUBLIC, anon, authenticated, service_role;
