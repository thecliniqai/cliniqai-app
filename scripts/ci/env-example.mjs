#!/usr/bin/env node
/**
 * `.env.example` generator (V2-03 03-01, I-07, R-15).
 *
 * Renders the template from the env schema's metadata (`ENV_DOCS`, `RETIRED_NAMES`, `PLATFORM_NAMES` in lib/env.ts):
 * every name the app reads, its rules and a non-secret example or placeholder. The file is generated, never edited by
 * hand: a plan that adds an env name updates lib/env.ts and re-runs this script in the same commit.
 *
 *   node scripts/ci/env-example.mjs           writes .env.example
 *   node scripts/ci/env-example.mjs --check   exit 1 when .env.example differs from the schema (CI `static`)
 *   node scripts/ci/env-example.mjs --stdout  prints the rendered template (the schema's text, not the file)
 *   --root <dir>                              use <dir>/.env.example instead of the repository's
 *
 * Neither mode prints the file's current content: `--check` reports only whether it matches.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { tsImport } from "tsx/esm/api";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const rootArg = process.argv.indexOf("--root");
// `--root <dir>` points the writer/checker at another checkout (the script's own spec uses a temp directory).
const ROOT = rootArg > -1 ? resolve(process.argv[rootArg + 1]) : REPO;
const TARGET = join(ROOT, ".env.example");

export async function renderEnvExample() {
  const { ENV_DOCS, RETIRED_NAMES, PLATFORM_NAMES, APP_ENVS, SET_IN_VERCEL } = await tsImport("../../lib/env.ts", import.meta.url);
  const lines = [
    "# GENERATED by `node scripts/ci/env-example.mjs` from lib/env.ts. Do not edit; CI `static` checks it is in sync.",
    "#",
    "# Names the clinicOS app reads. Copy to .env.local for `next dev` and fill real values there (never commit them).",
    `# APP_ENV selects the tier rules: ${APP_ENVS.join(" | ")}. staging and production are fail-closed:`,
    "# `next build`, `next start` and every server instance refuse to start when a rule below is broken.",
    "# Values here are examples or placeholders (<...>), never real values.",
  ];

  let group = null;
  for (const [name, doc] of Object.entries(ENV_DOCS)) {
    if (doc.group !== group) {
      group = doc.group;
      lines.push("", `# --- ${group} ---`);
    }
    for (const note of doc.notes) lines.push(`# ${note}`);
    // Deployment-only secrets stay commented out, so a copy of the template is a valid local configuration.
    lines.push(doc.example === SET_IN_VERCEL ? `# ${name}=${doc.example}` : `${name}=${doc.example}`);
  }

  lines.push("", "# --- Set by the platform (do not set by hand) ---");
  for (const [name, why] of Object.entries(PLATFORM_NAMES)) lines.push(`# ${name}: ${why}`);

  lines.push("", "# --- Retired names: setting any of these fails boot in staging and production ---");
  for (const [name, why] of Object.entries(RETIRED_NAMES)) lines.push(`# ${name}: ${why}`);

  return `${lines.join("\n")}\n`;
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const rendered = await renderEnvExample();

  if (args.has("--stdout")) {
    process.stdout.write(rendered);
    return;
  }
  if (args.has("--check")) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : null;
    if (current === rendered) {
      console.log("env-example: .env.example matches lib/env.ts");
      return;
    }
    console.error(
      current === null
        ? "env-example: .env.example is missing; run `node scripts/ci/env-example.mjs`"
        : "env-example: .env.example is out of date with lib/env.ts; run `node scripts/ci/env-example.mjs` and commit it",
    );
    process.exitCode = 1;
    return;
  }
  writeFileSync(TARGET, rendered);
  console.log("env-example: wrote .env.example from lib/env.ts");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
