#!/usr/bin/env node
/**
 * The dashboard's route patterns for client render error reports (V2-06 06-09a M-ERRCAP; T-06-09, T-06-10).
 *
 * `reportClientRenderError` stores a client-reported route only if it is one of the app's own dashboard route patterns
 * (anything else becomes `/`), so nothing a caller types reaches `ops.error_events` and the number of distinct client
 * keys is bounded by the app, not by input. The list is generated from the route tree, never typed by hand:
 * every `page.{tsx,ts,jsx,js}` under `app/(dashboard)/`, with route groups `(x)` removed and dynamic segments kept as
 * written (`[id]`, `[...slug]`); private `_folders`, parallel `@slots` and intercepting `(.)` segments are skipped.
 *
 * Usage: node scripts/observability/client-routes.mjs [--write | --check]
 *   --write  rewrite lib/observability/client-routes.ts
 *   --check  exit 1 when that file differs from the route tree (tests/observability/client-routes.spec.ts runs this)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const ROOT_DIR = "app/(dashboard)";
const OUT = "lib/observability/client-routes.ts";
const PAGE = /^page\.(tsx|ts|jsx|js)$/;

/** Route patterns of every page under `root/app/(dashboard)`, sorted. */
export function dashboardRoutePatterns(root = REPO) {
  const base = join(root, ROOT_DIR);
  if (!existsSync(base)) throw new Error(`${ROOT_DIR} not found under ${root}`);
  const out = new Set();
  const walk = (dir, segments) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isFile() && PAGE.test(entry.name)) out.add(`/${segments.join("/")}`);
      if (!entry.isDirectory()) continue;
      const name = entry.name;
      if (name.startsWith("_") || name.startsWith("@") || /^\(\.+\)/.test(name)) continue;
      const group = /^\(.+\)$/.test(name);
      walk(join(dir, name), group ? segments : [...segments, name]);
    }
  };
  walk(base, []);
  return [...out].sort();
}

export function renderModule(patterns) {
  const lines = patterns.map((p) => `  ${JSON.stringify(p)},`).join("\n");
  return `/**
 * GENERATED by scripts/observability/client-routes.mjs from app/(dashboard)/ (V2-06 06-09a M-ERRCAP). Do not edit:
 * run \`node scripts/observability/client-routes.mjs --write\` after adding or moving a dashboard page;
 * tests/observability/client-routes.spec.ts fails while this list and the route tree differ.
 *
 * The only routes a client render error report may store (lib/observability/client-render-event.ts).
 */
export const CLIENT_ROUTE_PATTERNS = [
${lines}
] as const;
`;
}

function main() {
  const mode = process.argv[2];
  const expected = renderModule(dashboardRoutePatterns());
  const file = join(REPO, OUT);
  if (mode === "--write") {
    writeFileSync(file, expected);
    console.log(`client-routes: wrote ${OUT}`);
    return 0;
  }
  if (mode === "--check") {
    const actual = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (actual === expected) {
      console.log(`client-routes: ${OUT} matches the route tree`);
      return 0;
    }
    console.error(`client-routes: ${OUT} differs from app/(dashboard)/; run node scripts/observability/client-routes.mjs --write`);
    return 1;
  }
  console.error("usage: node scripts/observability/client-routes.mjs --write | --check");
  return 2;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
