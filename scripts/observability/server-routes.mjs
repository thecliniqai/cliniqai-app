#!/usr/bin/env node
/**
 * The app's route patterns for the server timing lines (V2-09e 09E-02, R-20).
 *
 * `proxy.ts` forwards the request's route pattern to the handler (`x-clinicos-route`) so the `request.timing` line names the
 * screen or route and never the concrete path. The patterns are generated from the route tree, never typed by hand: every
 * `page.*` and `route.*` file under `app/`, route groups `(x)` removed, dynamic segments kept as written (`[id]`); private
 * `_folders`, parallel `@slots` and intercepting `(.)` segments are skipped. A file that is itself the route (`sw.js/route.ts`)
 * keeps its folder name.
 *
 * Usage: node scripts/observability/server-routes.mjs [--write | --check]
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const ROOT_DIR = "app";
const OUT = "lib/observability/server-routes.ts";
const ENTRY = /^(page|route)\.(tsx|ts|jsx|js)$/;

/** Route patterns of every page and route handler under `root/app`, sorted. */
export function serverRoutePatterns(root = REPO) {
  const base = join(root, ROOT_DIR);
  if (!existsSync(base)) throw new Error(`${ROOT_DIR} not found under ${root}`);
  const out = new Set();
  const walk = (dir, segments) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isFile() && ENTRY.test(entry.name)) out.add(`/${segments.join("/")}`);
      if (!entry.isDirectory()) continue;
      const name = entry.name;
      if (name.startsWith("_") || name.startsWith("@") || /^\(\.+\)/.test(name)) continue;
      const group = /^\(.+\)$/.test(name);
      walk(join(dir, name), group ? segments : [...segments, name]);
    }
  };
  walk(base, []);
  return [...out].sort();
}

export function renderModule(patterns) {
  const lines = patterns.map((p) => `  ${JSON.stringify(p)},`).join("\n");
  return `/**
 * GENERATED by scripts/observability/server-routes.mjs from app/ (V2-09e 09E-02, R-20). Do not edit: run
 * \`node scripts/observability/server-routes.mjs --write\` after adding or moving a page or route handler;
 * tests/observability/server-routes.spec.ts fails while this list and the route tree differ.
 *
 * The only route patterns a \`request.timing\` line may carry (lib/observability/route-patterns.ts).
 */
export const SERVER_ROUTE_PATTERNS = [
${lines}
] as const;
`;
}

function main() {
  const mode = process.argv[2];
  const expected = renderModule(serverRoutePatterns());
  const file = join(REPO, OUT);
  if (mode === "--write") {
    writeFileSync(file, expected);
    console.log(`server-routes: wrote ${OUT}`);
    return 0;
  }
  if (mode === "--check") {
    const actual = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (actual === expected) {
      console.log(`server-routes: ${OUT} matches the route tree`);
      return 0;
    }
    console.error(`server-routes: ${OUT} differs from app/; run node scripts/observability/server-routes.mjs --write`);
    return 1;
  }
  console.error("usage: node scripts/observability/server-routes.mjs --write | --check");
  return 2;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
