#!/usr/bin/env node
/**
 * Schema + privilege snapshot (V2-03 03-13b, review finding M-DRIFT; BACKEND_MIGRATION_PLAN B1).
 *
 * `supabase db diff` (migra) compares tables, columns and functions, but not privileges, and the staging diff used to
 * read only `public`. This phase's protections live in grants, policies and the `ops` / `private` schemas (REVOKE/GRANT
 * pairs on RPCs, column-level `GRANT INSERT (…)` on `payments`, `private.*` helpers, `ops.*` tables). This tool reads the
 * catalogue into one sorted text line per fact and compares it with the committed snapshot
 * `scripts/drift/schema-snapshot.txt`:
 *   - schemas `public`, `ops`, `private`, `authz` (`authz`: V2-05 05-01b): relations (kind, RLS enabled/forced),
 *     columns (type, not null, default, identity, generated), constraints, indexes, triggers, policies, functions
 *     (signature, result, language, security definer, volatility, `SET` config, md5 of the body), enum labels, view
 *     definitions (md5);
 *   - `storage.objects` / `storage.buckets` policies (app-owned; the storage tables themselves are Supabase's);
 *   - privileges held by `anon`, `authenticated`, `service_role` and `PUBLIC`: schema, table, column, sequence and
 *     function grants (NULL ACLs expanded to the built-in defaults), and default privileges in those schemas.
 * Objects that belong to an extension (e.g. `pg_trgm` in `public`) are left out: their version is the platform's.
 * Owners are not compared.
 *
 * Two uses:
 *   - CI `test` job (local half): after `supabase start` has applied every migration to a fresh stack, `--local --check`
 *     fails when the result differs from the committed snapshot. A migration that changes schema or privileges must
 *     ship the regenerated snapshot (`--local --write` after `npx supabase db reset --local`), so the reviewed diff
 *     shows exactly which grants and policies changed.
 *   - `drift.yml` `schema` job (hosted half, through scripts/staging/schema-drift.mjs): the same query runs read-only
 *     against staging (`STAGING_DB_URL_RO`, `clinicos_drift_ro`; catalogue reads only) and is compared with the
 *     snapshot of the checked-out `feature/v2`, so a dashboard grant to `anon` or an `ops` change on staging is drift.
 *
 * Usage:
 *   node scripts/drift/schema-snapshot.mjs --local --write              regenerate the committed snapshot
 *   node scripts/drift/schema-snapshot.mjs --local --check [--out <dir>] compare the local stack with it
 *   node scripts/drift/schema-snapshot.mjs --input <file> [--out <dir>]  compare a saved snapshot (tests)
 * `--out` writes `schema-snapshot-drift.json` (missing and unexpected lines). Exit 0 = equal, 1 = drift, 2 = the
 * snapshot could not be read. The local mode talks only to the local stack's container (`docker exec … psql`).
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const SNAPSHOT_FILE = path.join(REPO_ROOT, "scripts/drift/schema-snapshot.txt");
export const SNAPSHOT_SCHEMAS = ["public", "ops", "private", "authz"];
export const SNAPSHOT_ROLES = ["anon", "authenticated", "service_role"];
const HEADER = "# Generated by scripts/drift/schema-snapshot.mjs --local --write. Do not edit by hand.";

const schemaList = SNAPSHOT_SCHEMAS.map((s) => `'${s}'`).join(", ");
const roleList = SNAPSHOT_ROLES.map((r) => `'${r}'`).join(", ");

/**
 * One catalogue query; every row is one line `kind name detail`. Read-only (catalogue tables and pg_get_* functions,
 * which every role may call), so it runs as the read-only drift role on staging.
 */
export const SNAPSHOT_SQL = `
with
  ns as (select oid, nspname from pg_namespace where nspname in (${schemaList})),
  ext as (select classid, objid from pg_depend where deptype = 'e'),
  grantee_names as (
    select oid, rolname as name from pg_roles where rolname in (${roleList})
    union all select 0::oid, 'PUBLIC'
  ),
  rels as (
    select c.oid, c.relname, c.relkind, c.relrowsecurity, c.relforcerowsecurity, c.relacl, c.relowner, n.nspname
    from pg_class c join ns n on n.oid = c.relnamespace
    where c.relkind in ('r', 'p', 'v', 'm', 'f', 'S')
      and not exists (select 1 from ext where ext.classid = 'pg_class'::regclass and ext.objid = c.oid)
  ),
  procs as (
    select p.*, n.nspname, format('%I.%I(%s)', n.nspname, p.proname, pg_get_function_identity_arguments(p.oid)) as sig
    from pg_proc p join ns n on n.oid = p.pronamespace
    where not exists (select 1 from ext where ext.classid = 'pg_proc'::regclass and ext.objid = p.oid)
  ),
  lines(line) as (
    select format('relation %I.%I kind=%s rls=%s force_rls=%s', nspname, relname, relkind, relrowsecurity, relforcerowsecurity)
    from rels
    union all
    select format('column %I.%I.%I %s not_null=%s default=%s identity=%s generated=%s', r.nspname, r.relname, a.attname,
      format_type(a.atttypid, a.atttypmod), a.attnotnull, coalesce(pg_get_expr(d.adbin, d.adrelid), '-'),
      coalesce(nullif(a.attidentity, ''), '-'), coalesce(nullif(a.attgenerated, ''), '-'))
    from rels r join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where r.relkind in ('r', 'p', 'v', 'm', 'f')
    union all
    select format('constraint %I.%I.%I %s', r.nspname, r.relname, co.conname, pg_get_constraintdef(co.oid))
    from rels r join pg_constraint co on co.conrelid = r.oid
    union all
    select format('index %I.%I %s', r.nspname, i.relname, pg_get_indexdef(i.oid))
    from rels r join pg_index x on x.indrelid = r.oid join pg_class i on i.oid = x.indexrelid
    union all
    select format('trigger %I.%I.%I %s', r.nspname, r.relname, t.tgname, pg_get_triggerdef(t.oid))
    from rels r join pg_trigger t on t.tgrelid = r.oid and not t.tgisinternal
    union all
    select format('policy %I.%I.%I cmd=%s permissive=%s roles=%s using=%s check=%s', n.nspname, c.relname, p.polname,
      p.polcmd, p.polpermissive,
      (select coalesce(string_agg(case when rid = 0 then 'PUBLIC' else rid::regrole::text end, ',' order by 1), '-')
         from unnest(p.polroles) rid),
      coalesce(pg_get_expr(p.polqual, p.polrelid), '-'), coalesce(pg_get_expr(p.polwithcheck, p.polrelid), '-'))
    from pg_policy p join pg_class c on c.oid = p.polrelid join pg_namespace n on n.oid = c.relnamespace
    where n.nspname in (${schemaList}) or (n.nspname = 'storage' and c.relname in ('objects', 'buckets'))
    union all
    select format('function %s returns %s lang=%s security_definer=%s volatility=%s config=%s body_md5=%s', p.sig,
      coalesce(pg_get_function_result(p.oid), '-'), l.lanname, p.prosecdef, p.provolatile,
      coalesce((select string_agg(c, ',' order by c) from unnest(p.proconfig) c), '-'), md5(coalesce(p.prosrc, '')))
    from procs p join pg_language l on l.oid = p.prolang
    union all
    select format('enum %I.%I %s', n.nspname, t.typname,
      (select string_agg(e.enumlabel, ',' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid))
    from pg_type t join ns n on n.oid = t.typnamespace
    where t.typtype = 'e' and not exists (select 1 from ext where ext.classid = 'pg_type'::regclass and ext.objid = t.oid)
    union all
    select format('view %I.%I md5=%s', nspname, relname, md5(pg_get_viewdef(oid))) from rels where relkind in ('v', 'm')
    union all
    select format('grant schema %I %s to %s', n.nspname, a.privilege_type, g.name)
    from pg_namespace n, aclexplode(coalesce(n.nspacl, acldefault('n', n.nspowner))) a, grantee_names g
    where n.nspname in (${schemaList}) and a.grantee = g.oid
    union all
    select format('grant %s %I.%I %s to %s', case when r.relkind = 'S' then 'sequence' else 'table' end, r.nspname, r.relname,
      a.privilege_type, g.name)
    from rels r, aclexplode(coalesce(r.relacl, acldefault(case when r.relkind = 'S' then 's' else 'r' end::"char", r.relowner))) a,
      grantee_names g
    where a.grantee = g.oid
    union all
    select format('grant column %I.%I.%I %s to %s', r.nspname, r.relname, at.attname, a.privilege_type, g.name)
    from rels r join pg_attribute at on at.attrelid = r.oid and at.attnum > 0 and not at.attisdropped and at.attacl is not null,
      aclexplode(at.attacl) a, grantee_names g
    where a.grantee = g.oid
    union all
    select format('grant function %s %s to %s', p.sig, a.privilege_type, g.name)
    from procs p, aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a, grantee_names g
    where a.grantee = g.oid
    union all
    select format('default-privilege %I %s %s to %s', n.nspname, d.defaclobjtype, a.privilege_type, g.name)
    from pg_default_acl d join ns n on n.oid = d.defaclnamespace, aclexplode(d.defaclacl) a, grantee_names g
    where a.grantee = g.oid
  )
-- Multi-line expressions (policy USING bodies) become one line, so every fact is exactly one row.
select regexp_replace(line, '\s*\n\s*', ' ', 'g') collate "C" as line from lines order by 1;
`;

/** psql arguments that run the snapshot in one read-only transaction, one unaligned line per row. */
export function psqlArgs() {
  return ["-v", "ON_ERROR_STOP=1", "-qAt", "-c", "begin read only", "-c", SNAPSHOT_SQL, "-c", "rollback"];
}

/** Snapshot lines from text: comments and blank lines dropped. */
export function parseSnapshot(text) {
  return text
    .split("\n")
    .map((l) => l.trimEnd())
    .filter((l) => l !== "" && !l.startsWith("#"));
}

/** Lines the expected snapshot has that the actual one lacks, and the reverse. */
export function compareSnapshots(expected, actual) {
  const want = new Set(expected);
  const have = new Set(actual);
  return {
    missing: expected.filter((l) => !have.has(l)),
    unexpected: actual.filter((l) => !want.has(l)),
  };
}

/** Renders the committed file. */
export function renderSnapshot(lines) {
  return `${HEADER}\n${lines.join("\n")}\n`;
}

function localContainer() {
  const toml = fs.readFileSync(path.join(REPO_ROOT, "supabase/config.toml"), "utf8");
  const projectId = /^project_id\s*=\s*"([^"]+)"/m.exec(toml)?.[1];
  if (!projectId) throw new Error("project_id not found in supabase/config.toml");
  return `supabase_db_${projectId}`;
}

/**
 * The local stack's snapshot: `docker exec supabase_db_<project_id> psql` (loopback by construction: a container name,
 * never a URL).
 * @param {(cmd: string, args: string[], opts: object) => { status: number | null, stdout: string, stderr: string, error?: Error }} [spawnImpl]
 */
export function localSnapshot(spawnImpl = spawnSync) {
  const r = spawnImpl("docker", ["exec", localContainer(), "psql", "-U", "postgres", ...psqlArgs()], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (r.error || r.status !== 0) throw new Error(`psql on the local stack failed (exit ${r.status}): ${String(r.stderr ?? "").trim()}`);
  return parseSnapshot(String(r.stdout ?? ""));
}

/**
 * Compares `actual` with the committed snapshot. Returns { exitCode, lines } (lines for the log) and writes the JSON
 * report to `out` when given.
 */
export function judgeSnapshot(actual, { expected = parseSnapshot(fs.readFileSync(SNAPSHOT_FILE, "utf8")), out, label = "local" } = {}) {
  const { missing, unexpected } = compareSnapshots(expected, actual);
  if (out) {
    fs.mkdirSync(out, { recursive: true });
    const report = {
      tool: "scripts/drift/schema-snapshot.mjs",
      target: label,
      expected_lines: expected.length,
      actual_lines: actual.length,
      missing,
      unexpected,
      result: missing.length + unexpected.length === 0 ? "pass" : "fail",
    };
    fs.writeFileSync(path.join(out, "schema-snapshot-drift.json"), `${JSON.stringify(report, null, 2)}\n`);
  }
  if (missing.length + unexpected.length === 0) {
    return { exitCode: 0, lines: [`schema-snapshot: PASS (${label}: ${actual.length} lines equal the committed snapshot)`] };
  }
  return {
    exitCode: 1,
    lines: [
      `schema-snapshot: FAIL (${label}: ${missing.length} line(s) missing, ${unexpected.length} unexpected vs scripts/drift/schema-snapshot.txt)`,
      ...missing.map((l) => `- ${l}`),
      ...unexpected.map((l) => `+ ${l}`),
      "A schema/privilege change outside the migrations, or a migration without its regenerated snapshot",
      "(npx supabase db reset --local && node scripts/drift/schema-snapshot.mjs --local --write).",
    ],
  };
}

function main(argv) {
  const has = (f) => argv.includes(f);
  const val = (f) => (argv.indexOf(f) > -1 ? argv[argv.indexOf(f) + 1] : undefined);
  const out = val("--out") ? path.resolve(val("--out")) : undefined;
  try {
    if (has("--input")) {
      const actual = parseSnapshot(fs.readFileSync(path.resolve(val("--input")), "utf8"));
      const r = judgeSnapshot(actual, { out, label: "input" });
      for (const l of r.lines) (r.exitCode === 0 ? console.log : console.error)(l);
      return r.exitCode;
    }
    if (has("--local") && has("--write")) {
      const lines = localSnapshot();
      fs.writeFileSync(SNAPSHOT_FILE, renderSnapshot(lines));
      console.log(`schema-snapshot: wrote ${lines.length} lines to scripts/drift/schema-snapshot.txt`);
      return 0;
    }
    if (has("--local") && has("--check")) {
      const r = judgeSnapshot(localSnapshot(), { out, label: "local" });
      for (const l of r.lines) (r.exitCode === 0 ? console.log : console.error)(l);
      return r.exitCode;
    }
  } catch (e) {
    console.error(`schema-snapshot: ${e instanceof Error ? e.message : String(e)}`);
    return 2;
  }
  console.error("usage: node scripts/drift/schema-snapshot.mjs (--local --write | --local --check [--out <dir>] | --input <file> [--out <dir>])");
  return 2;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exit(main(process.argv.slice(2)));
}
